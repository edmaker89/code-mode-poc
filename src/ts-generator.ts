/**
 * Generates TypeScript declarations from MCP tool schemas
 * This mimics what Cloudflare's Code Mode does automatically
 */
import { MCPTool } from "./mcp-client.js";

export interface TSDefinition {
  interfaces: string;
  apiDeclaration: string;
}

/**
 * Convert JSON Schema to TypeScript type
 */
function jsonSchemaToTS(schema: unknown, typeName: string): string {
  const s = schema as Record<string, unknown>;
  
  if (!s || s.type !== "object") {
    return "unknown";
  }

  const props = (s.properties as Record<string, unknown>) || {};
  const required = (s.required as string[]) || [];
  
  const fields = Object.entries(props).map(([key, prop]) => {
    const p = prop as Record<string, unknown>;
    const optional = !required.includes(key) ? "?" : "";
    const tsType = propToTSType(p);
    const desc = p.description ? ` /** ${escapeJsDoc(p.description as string)} */` : "";
    return `  ${key}${optional}: ${tsType};${desc}`;
  });

  return `{\n${fields.join("\n")}\n}`;
}

function propToTSType(prop: Record<string, unknown>): string {
  const type = prop.type as string;
  const format = prop.format as string | undefined;
  
  switch (type) {
    case "string":
      if (format === "date-time") return "Date";
      if (format === "uri") return "string";
      if (prop.enum) return prop.enum.map((v: unknown) => JSON.stringify(v)).join(" | ");
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      return `${propToTSType(prop.items as Record<string, unknown>)}[]`;
    case "object":
      return jsonSchemaToTS(prop, "Anonymous");
    default:
      return "unknown";
  }
}

function escapeJsDoc(str: string): string {
  return str.replace(/\*/g, "\\*").replace(/\n/g, " ");
}

function toPascalCase(str: string): string {
  return str
    .split(/[-_]/)
    .map(s => s.charAt(0).toUpperCase() + s.slice(1))
    .join("");
}

function toCamelCase(str: string): string {
  const pascal = toPascalCase(str);
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}

/**
 * Generate TypeScript definitions from MCP tools
 */
export function generateTSDefinitions(tools: MCPTool[], namespace = "mcp"): TSDefinition {
  const interfaces: string[] = [];
  const methods: string[] = [];

  for (const tool of tools) {
    const inputTypeName = `${toPascalCase(tool.name)}Input`;
    const outputTypeName = `${toPascalCase(tool.name)}Output`;
    const methodName = toCamelCase(tool.name);

    // Input interface
    interfaces.push(
      `interface ${inputTypeName} ${jsonSchemaToTS(tool.inputSchema, inputTypeName)}`
    );

    // Output interface (generic for now)
    interfaces.push(
      `interface ${outputTypeName} {\n  [key: string]: unknown;\n}`
    );

    // Method with JSDoc
    const desc = tool.description ? ` * ${escapeJsDoc(tool.description)}` : "";
    methods.push(
      `  /**${desc}\n   */\n  ${methodName}: (input: ${inputTypeName}) => Promise<${outputTypeName}>;`
    );
  }

  const interfacesStr = interfaces.join("\n\n");
  const apiDeclaration = `declare const ${namespace}: {\n${methods.join("\n\n")}\n};`;

  return {
    interfaces: interfacesStr,
    apiDeclaration,
  };
}

/**
 * Generate the complete sandbox context code
 * Outputs valid JavaScript (not TypeScript) for the vm sandbox
 * NOTE: The actual namespace object (e.g., 'mcp') is injected by the host via bindings
 * This context just provides user code area
 */
export function generateSandboxContext(
  tsDef: TSDefinition,
  namespace = "mcp"
): string {
  return `// ============================================
// CODE MODE SANDBOX CONTEXT (JavaScript Runtime)
// The '${namespace}' object is INJECTED by the host at runtime via bindings
// ============================================

// ============================================
// USER CODE GOES BELOW (generated by LLM)
// ============================================
// The LLM writes code here that uses the '${namespace}' API
// Results must be printed with console.log()
//
// Example:
// const result = await ${namespace}.searchFiles({ pattern: "*.ts" });
// console.log(JSON.stringify(result));
`;
}